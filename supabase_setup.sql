-- ==============================================================================
-- 8. TRIGGER PL/PGSQL: CÁLCULO DE VPD Y DISPARO EN LAZO CERRADO
-- ==============================================================================
CREATE OR REPLACE FUNCTION fn_procesar_telemetria_iot()
RETURNS TRIGGER AS $$
DECLARE
  v_es_temperatura FLOAT;
  v_vpd FLOAT;
  v_umbrales RECORD;
  v_actuador RECORD;
BEGIN
  -- A. Cálculo de Déficit de Presión de Vapor (VPD)
  IF NEW.temperatura_aire IS NOT NULL AND NEW.humedad_aire IS NOT NULL THEN
    v_es_temperatura := 0.61078 * exp((17.27 * NEW.temperatura_aire) / (NEW.temperatura_aire + 237.3));
    v_vpd := v_es_temperatura * (1.0 - (NEW.humedad_aire / 100.0));
    NEW.indice_vpd := round(v_vpd::numeric, 3);
  END IF;

  -- B. Actualizar última conexión en dispositivos_iot
  UPDATE public.dispositivos_iot 
  SET ultima_conexion = timezone('utc'::text, now()),
      estado_operativo = 'ACTIVO'
  WHERE dispositivo_id = NEW.dispositivo_id;

  -- C. Obtener configuración de umbrales y estado de actuadores
  SELECT * INTO v_umbrales FROM public.umbrales_agronomicos WHERE dispositivo_id = NEW.dispositivo_id;
  SELECT * INTO v_actuador FROM public.actuadores_iot WHERE dispositivo_id = NEW.dispositivo_id;

  IF FOUND AND v_umbrales IS NOT NULL THEN
    -- 1. Regla de Riego: Estrés hídrico (Humedad de suelo < umbral mínimo)
    IF NEW.humedad_suelo_pct IS NOT NULL AND NEW.humedad_suelo_pct < v_umbrales.hum_suelo_pct_min THEN
      INSERT INTO public.alertas_incidentes_iot (dispositivo_id, tipo_alerta, nivel_severidad, mensaje, valor_registrado, valor_umbral_limite)
      VALUES (
        NEW.dispositivo_id, 
        'ESTRES_HIDRICO', 
        'CRITICA', 
        'Humedad de sustrato bajo límite crítico (' || round(NEW.humedad_suelo_pct::numeric, 1) || '% < ' || v_umbrales.hum_suelo_pct_min || '%). Marchitez inminente.',
        NEW.humedad_suelo_pct,
        v_umbrales.hum_suelo_pct_min
      );

      -- Si está en modo automático y la bomba está apagada -> Encender Bomba (Relé 1)
      IF v_actuador.modo_auto = TRUE AND v_actuador.relay_1 = FALSE THEN
        UPDATE public.actuadores_iot 
        SET relay_1 = TRUE, 
            ultimo_cambio_por = 'ALGORITMO_CONTROL_RIEGO',
            actualizado_en = timezone('utc'::text, now())
        WHERE dispositivo_id = NEW.dispositivo_id;

        INSERT INTO public.auditoria_comandos_actuadores (dispositivo_id, actuador, estado_anterior, estado_nuevo, origen_comando, justificacion)
        VALUES (NEW.dispositivo_id, 'RELAY_1', FALSE, TRUE, 'TRIGGER_ALGORITMO', 'Activación automática de riego por humedad de suelo inferior a ' || v_umbrales.hum_suelo_pct_min || '%');
      END IF;
    END IF;

    -- 2. Regla de Ventilación: Sobrecalentamiento (Temperatura de aire > umbral máximo)
    IF NEW.temperatura_aire IS NOT NULL AND NEW.temperatura_aire > v_umbrales.temp_aire_max THEN
      INSERT INTO public.alertas_incidentes_iot (dispositivo_id, tipo_alerta, nivel_severidad, mensaje, valor_registrado, valor_umbral_limite)
      VALUES (
        NEW.dispositivo_id, 
        'SOBRECALENTAMIENTO', 
        'ALTA', 
        'Temperatura ambiental crítica (' || round(NEW.temperatura_aire::numeric, 1) || '°C > ' || v_umbrales.temp_aire_max || '°C). Estrés térmico vegetal.',
        NEW.temperatura_aire,
        v_umbrales.temp_aire_max
      );

      -- Si está en modo automático y el ventilador está apagado -> Encender Extractor (Relé 2)
      IF v_actuador.modo_auto = TRUE AND v_actuador.relay_2 = FALSE THEN
        UPDATE public.actuadores_iot 
        SET relay_2 = TRUE, 
            ultimo_cambio_por = 'ALGORITMO_CONTROL_VENTILACION',
            actualizado_en = timezone('utc'::text, now())
        WHERE dispositivo_id = NEW.dispositivo_id;

        INSERT INTO public.auditoria_comandos_actuadores (dispositivo_id, actuador, estado_anterior, estado_nuevo, origen_comando, justificacion)
        VALUES (NEW.dispositivo_id, 'RELAY_2', FALSE, TRUE, 'TRIGGER_ALGORITMO', 'Activación automática de ventilación por temperatura superior a ' || v_umbrales.temp_aire_max || '°C');
      END IF;
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_procesar_telemetria ON public.sensores_iot;
CREATE TRIGGER trg_procesar_telemetria
  BEFORE INSERT ON public.sensores_iot
  FOR EACH ROW
  EXECUTE FUNCTION fn_procesar_telemetria_iot();

