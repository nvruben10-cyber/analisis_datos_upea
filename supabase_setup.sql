-- ==============================================================================

-- 1. TABLA: Sensores IoT (Telemetría de campo)
CREATE TABLE IF NOT EXISTS public.sensores_iot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dispositivo_id TEXT NOT NULL,
  temperatura_aire FLOAT,       -- Medición DHT22 (°C)
  humedad_aire FLOAT,           -- Medición DHT22 (% RH)
  humedad_suelo_pct FLOAT,      -- YL-69 Capacitivo (0 - 100%)
  humedad_suelo_raw INT,        -- Valor analógico en bruto (0 - 1023)
  temperatura_suelo FLOAT,      -- Sonda sumergible DS18B20 (°C)
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Índices para optimizar consultas de series temporales y filtrado por dispositivo
CREATE INDEX IF NOT EXISTS idx_sensores_iot_dispositivo_creado 
  ON public.sensores_iot (dispositivo_id, creado_en DESC);

-- 2. TABLA: Actuadores IoT (Control de Relés y Automatización)
CREATE TABLE IF NOT EXISTS public.actuadores_iot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dispositivo_id TEXT NOT NULL UNIQUE,
  relay_1 BOOLEAN DEFAULT FALSE NOT NULL,                     -- Estado de Relé 1 (ej: Bomba de agua)
  relay_2 BOOLEAN DEFAULT FALSE NOT NULL,                     -- Estado de Relé 2 (ej: Ventilador/Extractor)
  relay_1_nombre TEXT DEFAULT 'Relé 1 (Bomba de Riego)',       -- Etiqueta descriptiva personalizable
  relay_2_nombre TEXT DEFAULT 'Relé 2 (Ventilador/Extractor)',-- Etiqueta descriptiva personalizable
  modo_auto BOOLEAN DEFAULT FALSE NOT NULL,                   -- Modo automático o manual
  actualizado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Disparador para actualizar automáticamente el campo 'actualizado_en'
CREATE OR REPLACE FUNCTION actualizar_timestamp_actuadores()
RETURNS TRIGGER AS $$
BEGIN
  NEW.actualizado_en = timezone('utc'::text, now());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_actualizar_actuadores ON public.actuadores_iot;
CREATE TRIGGER trigger_actualizar_actuadores
  BEFORE UPDATE ON public.actuadores_iot
  FOR EACH ROW
  EXECUTE FUNCTION actualizar_timestamp_actuadores();

-- 3. POLÍTICAS DE SEGURIDAD A NIVEL DE FILA (RLS)
ALTER TABLE public.sensores_iot ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.actuadores_iot ENABLE ROW LEVEL SECURITY;

-- Políticas para sensores_iot:
-- Permitir que dispositivos de campo inserten datos utilizando la clave pública anónima
DROP POLICY IF EXISTS "Permitir inserción anónima para dispositivos" ON public.sensores_iot;
CREATE POLICY "Permitir inserción anónima para dispositivos" 
  ON public.sensores_iot 
  FOR INSERT 
  WITH CHECK (true);

-- Permitir lectura a usuarios autenticados (Dashboard) y opcionalmente anónimo si se requiere
DROP POLICY IF EXISTS "Permitir lectura para usuarios autenticados" ON public.sensores_iot;
CREATE POLICY "Permitir lectura para usuarios autenticados" 
  ON public.sensores_iot 
  FOR SELECT 
  USING (auth.role() = 'authenticated' OR auth.role() = 'anon');

-- Políticas para actuadores_iot:
-- Permitir lectura a dispositivos IoT (para saber si deben encender/apagar) y al frontend
DROP POLICY IF EXISTS "Permitir lectura de actuadores" ON public.actuadores_iot;
CREATE POLICY "Permitir lectura de actuadores" 
  ON public.actuadores_iot 
  FOR SELECT 
  USING (true);

-- Permitir actualización de relés a usuarios autenticados (desde el dashboard web)
DROP POLICY IF EXISTS "Permitir actualización de relés a autenticados" ON public.actuadores_iot;
CREATE POLICY "Permitir actualización de relés a autenticados" 
  ON public.actuadores_iot 
  FOR UPDATE 
  USING (auth.role() = 'authenticated' OR auth.role() = 'anon')
  WITH CHECK (auth.role() = 'authenticated' OR auth.role() = 'anon');

-- 4. HABILITACIÓN DE REALTIME (Suscripción en vivo sin recargar la página)
ALTER PUBLICATION supabase_realtime ADD TABLE public.sensores_iot;
ALTER PUBLICATION supabase_realtime ADD TABLE public.actuadores_iot;

