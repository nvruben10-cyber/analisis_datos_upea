-- 9. VISTA ANALÍTICA RESUMEN DE 24 HORAS
-- ==============================================================================
CREATE OR REPLACE VIEW public.v_metricas_resumen_actual AS
SELECT 
  s.dispositivo_id,
  d.nombre_nodo,
  d.ubicacion_geografica,
  d.estado_operativo,
  d.ultima_conexion,
  COUNT(s.id) AS total_muestras_registradas,
  ROUND(AVG(s.temperatura_aire)::numeric, 2) AS promedio_temp_aire_24h,
  ROUND(MAX(s.temperatura_aire)::numeric, 2) AS max_temp_aire_24h,
  ROUND(MIN(s.temperatura_aire)::numeric, 2) AS min_temp_aire_24h,
  ROUND(AVG(s.humedad_aire)::numeric, 2) AS promedio_hum_aire_24h,
  ROUND(AVG(s.humedad_suelo_pct)::numeric, 2) AS promedio_hum_suelo_24h,
  ROUND(AVG(s.temperatura_suelo)::numeric, 2) AS promedio_temp_suelo_24h,
  ROUND(AVG(COALESCE(s.indice_vpd, 0.0))::numeric, 3) AS promedio_vpd_24h
FROM public.sensores_iot s
LEFT JOIN public.dispositivos_iot d ON d.dispositivo_id = s.dispositivo_id
WHERE s.creado_en >= timezone('utc'::text, now()) - INTERVAL '24 hours'
GROUP BY s.dispositivo_id, d.nombre_nodo, d.ubicacion_geografica, d.estado_operativo, d.ultima_conexion;

